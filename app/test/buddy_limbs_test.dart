// Buddy's arms and legs, of which there used to be one each.
//
// Twelve bodies, twelve eyes, two hats — and one arm, one leg. The shop had
// priced both categories at thirty coins since it was built and
// `buddy_shop_catalog.dart` said so in a comment: the single options are free
// "because they are currently the *only* options; when more land they price
// themselves off kBuddyPartPrices with no edit here". So two of the six
// categories in the shop showed one already-owned tile and nothing else, and
// the character creator hid them entirely.
//
// Three of each now: paws, mittens and wings; paw feet, boots and bird feet.
// The gating either side of that needed no code change, which is the part
// worth checking — a create-mode tab appears once she owns two of a kind, and
// a shop tab appears once anything in it costs money.

import 'dart:io';

import 'package:critmath/data/buddy_parts_catalog.dart';
import 'package:critmath/data/buddy_shop_catalog.dart';
import 'package:critmath/models/buddy_appearance.dart';
import 'package:critmath/ui/widgets/buddy_widget.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'support/harness.dart';

/// Every (id, left, right) the game can equip.
List<(String, String, String)> _pairs() => <(String, String, String)>[
      for (final o in kBuddyArms) (o.id, o.leftAsset, o.rightAsset),
      for (final o in kBuddyLegs) (o.id, o.leftAsset, o.rightAsset),
    ];

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() => SharedPreferences.setMockInitialValues({}));

  group('the sprites', () {
    test('are on disk, both halves of every pair', () {
      // A pair whose left half is missing does not fail loudly — the right arm
      // draws and the left is a blank gap, which reads as Buddy having lost an
      // arm rather than as a broken build.
      for (final (id, left, right) in _pairs()) {
        expect(File(left).existsSync(), isTrue, reason: '$id left');
        expect(File(right).existsSync(), isTrue, reason: '$id right');
      }
    });

    test('and the two halves are different files', () {
      // The left is generated by mirroring the right (tools/artgen `mirror`).
      // Pointing both at the same file would give Buddy two right arms, which
      // at this size is subtle enough to survive a glance.
      for (final (id, left, right) in _pairs()) {
        expect(left, isNot(right), reason: '$id uses one sprite twice');
      }
    });

    test('and no two pairs share one', () {
      final all = <String>[
        for (final (_, left, right) in _pairs()) ...[left, right],
      ];
      expect(all.toSet(), hasLength(all.length));
    });

    test('and the folders are declared in pubspec', () {
      final pubspec = File('pubspec.yaml').readAsStringSync();
      for (final (_, left, right) in _pairs()) {
        for (final path in [left, right]) {
          final dir = '${path.substring(0, path.lastIndexOf('/'))}/';
          expect(pubspec, contains(dir), reason: '$dir not bundled');
        }
      }
    });
  });

  group('the shop', () {
    test('now has something to sell in both categories', () {
      // This is the condition `_availableCategories` uses to decide whether a
      // shop tab exists at all, so it is the difference between two visible
      // categories and two absent ones.
      for (final kind in [BuddyPartKind.arms, BuddyPartKind.legs]) {
        final forSale = buddyPartsOfKind(kind)
            .where((p) => buddyPartPrice(kind, p.id) > 0)
            .toList();
        expect(
          forSale,
          isNotEmpty,
          reason: '${kind.name} would still be missing from the shop',
        );
      }
    });

    test('and charges the price the category was always set to', () {
      expect(buddyPartPrice(BuddyPartKind.arms, 'arm-2'), 30);
      expect(buddyPartPrice(BuddyPartKind.legs, 'leg-2'), 30);
    });

    test('but the starter pair stays free', () {
      // The first arm and the first leg are what a brand-new Buddy is wearing.
      // Charging for either would leave a fresh save unable to render.
      expect(buddyPartPrice(BuddyPartKind.arms, 'arm-1'), 0);
      expect(buddyPartPrice(BuddyPartKind.legs, 'leg-1'), 0);
    });

    test('and a fresh save owns exactly one of each', () {
      // Which is also what keeps the *creator* from growing two new tabs on
      // first run: a create-mode category needs two owned before it earns one,
      // and onboarding is not a storefront.
      for (final kind in ['arms', 'legs']) {
        expect(
          kBuddyFreeParts.where((k) => k.startsWith('$kind:')),
          hasLength(1),
          reason: 'a new Buddy would open the creator on a $kind tab',
        );
      }
    });
  });

  group('on Buddy', () {
    testWidgets('every arm and every leg renders', (tester) async {
      // The sprites are drawn into fixed fractional boxes and each arm is
      // rotated about its shoulder, so a sprite framed differently from the
      // one it replaces does not fail — it swings from the wrong end. This
      // cannot see that. What it catches is a catalog entry pointing at
      // nothing, which throws at paint.
      useViewSize(tester, const Size(600, 600));

      for (var i = 0; i < kBuddyArms.length; i++) {
        await tester.pumpWidget(
          ProviderScope(
            child: MaterialApp(
              home: Scaffold(
                body: Center(
                  child: BuddyWidget(
                    size: 300,
                    appearance: BuddyAppearance(
                      bodyId: 'gold',
                      eyesId: 'v1',
                      mouthId: 'v1',
                      armsId: kBuddyArms[i].id,
                      legsId: kBuddyLegs[i % kBuddyLegs.length].id,
                    ),
                  ),
                ),
              ),
            ),
          ),
        );
        await tester.pump(const Duration(milliseconds: 50));
        expect(
          tester.takeException(),
          isNull,
          reason: 'threw on ${kBuddyArms[i].id}',
        );
      }
    });

    test('and the default Buddy still wears a pair that exists', () {
      final defaults = BuddyAppearance.defaults();
      expect(kBuddyArms.map((a) => a.id), contains(defaults.armsId));
      expect(kBuddyLegs.map((l) => l.id), contains(defaults.legsId));
    });
  });
}
